import pandas as pd
import joblib

df=pd.read_csv('신체검사.csv')

lr_model = joblib.load('lr_model.pkl')
rf_clf = joblib.load('rf_clf.pkl')

def generate_weight_loss_plan(current_height, current_chest, current_waist, target_weight):
    # 1. 선형 회귀 모델 기반 현재 몸무게 예측
    input_df = pd.DataFrame([[current_height, current_chest, current_waist]],
                            columns=['height', 'chest', 'waist'])
    predicted_weight = lr_model.predict(input_df)[0]

    # 현재 상태 비만 단계 예측
    input_current = pd.DataFrame([[current_height, current_chest, current_waist, predicted_weight]],
                                 columns=['height', 'chest', 'waist', 'weight'])

    pred_obesity_rf = rf_clf.predict(input_current)[0]

    # 감량해야 할 목표 체중 계산
    weight_to_lose = predicted_weight - target_weight

    print("=" * 100)
    print(f"[현재 신체 정보] 키: {current_height}cm | 가슴둘레: {current_chest}cm | 허리둘레: {current_waist}cm | 비만단계: {pred_obesity_rf}")
    print(f"[체중 분석] 현재 예측 몸무게: {predicted_weight:.1f}kg  ---> 목표 몸무게: {target_weight:.1f}kg")

    if weight_to_lose <= 0:
        print("이미 목표 체중 이하이거나 감량이 필요하지 않은 상태입니다!")
        print("-" * 100)
        return

    print(f"총 감량 목표: {weight_to_lose:.1f}kg")
    print("-" * 100)

    # 2. 선형 회귀 계수 추출 (가중치)
    coef_chest = lr_model.coef_[1]
    coef_waist = lr_model.coef_[2]


    # 3. 신체 사이즈 감량 시나리오 계산

    # 시나리오1: 허리둘레 집중 감량
    waist_reduction_only = weight_to_lose / coef_waist
    target_waist_only = current_waist - waist_reduction_only

    input_target_1 = pd.DataFrame([[current_height, current_chest, target_waist_only, target_weight]],
                                  columns=['height', 'chest', 'waist', 'weight'])

    pred_obesity_target_1 = rf_clf.predict(input_target_1)[0]

    print("[시나리오 1] 허리둘레 위주 체지방 감량 가이드")
    print(f"  • 허리둘레 목표: {current_waist}cm --> {target_waist_only:.1f}cm (약 {waist_reduction_only:.1f}cm 감량 필요)")
    print(f"  • 비만단계 변화: {pred_obesity_rf} --> {pred_obesity_target_1}")
    print("  • 추천 운동: 유산소(러닝, 인터벌 유산소) + 복근/코어 운동(플랭크, 크런치, 레그레이즈)\n")

    # 시나리오 2: 허리 70% + 가슴 30% 균형 감량
    target_weight_loss_waist = weight_to_lose * 0.7
    target_weight_loss_chest = weight_to_lose * 0.3

    waist_reduction_balanced = target_weight_loss_waist / coef_waist
    chest_reduction_balanced = target_weight_loss_chest / coef_chest

    target_waist_balanced = current_waist - waist_reduction_balanced
    target_chest_balanced = current_chest - chest_reduction_balanced


    input_target_2 = pd.DataFrame([[current_height, target_chest_balanced, target_waist_balanced, target_weight]],
                                  columns=['height', 'chest', 'waist', 'weight'])

    pred_obesity_target_2 = rf_clf.predict(input_target_2)[0]

    print("[시나리오 2] 전신 균형 감량 가이드 (허리 70% + 가슴/상체 30%)")
    print(f"  • 허리둘레 목표: {current_waist}cm --> {target_waist_balanced:.1f}cm (약 {waist_reduction_balanced:.1f}cm 감량 필요)")
    print(f"  • 가슴둘레 목표: {current_chest}cm --> {target_chest_balanced:.1f}cm (약 {chest_reduction_balanced:.1f}cm 감량 필요)")
    print(f"  • 비만단계 변화: {pred_obesity_rf} --> {pred_obesity_target_2}")
    print("  • 추천 운동: 전신 유산소 + 상체 근력 운동(푸시업, 덤벨 숄더프레스, 렛풀다운)으로 근선명도 유지")
    print("=" * 100)


h = float(input("키: "))
c = float(input("가슴둘레: "))
w = float(input("허리둘레: "))
w2 = float(input("목표 몸무게: "))

generate_weight_loss_plan(h, c, w, w2)

